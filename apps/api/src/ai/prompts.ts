import type { CardContextDto } from './dto/card-context.dto'

const STYLE = `Стиль: информативно, факты важнее оценок, короткие абзацы. Можно использовать Markdown, код оформляй в блоках с тремя обратными апострофами.`

export function askSystemPrompt(card: CardContextDto): string {
  return `Ты репетитор и объясняешь тему карточки старшему фронтенд-разработчику.
${STYLE}
Отвечай на уточняющие вопросы пользователя по теме карточки. Объем ответа до 250 слов, если пользователь не просит подробнее.

Контекст карточки.
Заметка: ${card.noteTitle}
Вопрос: ${card.question}
Ответ: ${card.answer}`
}

export function advicePrompt(mistakes: CardContextDto[]): { system: string; user: string } {
  const system = `Ты помогаешь повторить материал по карточкам, на которых пользователь ошибся.
${STYLE}
Назови 2-4 темы для повторения. Для каждой укажи, что именно перечитать и в какой заметке (по названию). Ответ оформи маркированным списком Markdown. Без общих слов поддержки и мотивации.`
  const user = mistakes
    .map(({ noteTitle, question, answer }, index) => `${index + 1}. Заметка: ${noteTitle}\nВопрос: ${question}\nОтвет: ${answer}`)
    .join('\n\n')
  return { system, user: `Карточки с ошибками:\n\n${user}` }
}

